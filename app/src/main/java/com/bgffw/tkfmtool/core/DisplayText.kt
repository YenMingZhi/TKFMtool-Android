    private const val NO_TAG = "无词条"
    private const val NO_TAG_DISPLAY = "無標籤"

    fun tag(text: String): String =
        if (text == NO_TAG) NO_TAG_DISPLAY else TraditionalChinese.toTraditional(text)

    /** `3☆魔王 巴尔` → `3☆魔王 巴爾`。星級前綴保留，結果面板靠它決定顏色。 */
    fun characterName(cell: String): String {
        val star = cell.indexOf('☆')
        val prefix = cell.substring(0, star + 1)
        val name = cell.substring(star + 1)
        return prefix + (CHARACTER_NAMES[name] ?: TraditionalChinese.toTraditional(name))
    }

    /** 角色庫的一整列：第一欄是角色名，其餘是標籤。 */
    fun row(cells: List<String>): String =
        cells.mapIndexed { index, cell ->
            if (index == 0) characterName(cell) else tag(cell)
        }.joinToString(",")
